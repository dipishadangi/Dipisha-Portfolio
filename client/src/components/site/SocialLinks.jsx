const ALIASES = { twitter: 'x', email: 'mail', website: 'link' };

/** Icons drawn with a stroke rather than a solid fill. */
const STROKED = new Set(['mail', 'link']);

export const SOCIAL_ICON_NAMES = Object.keys(GLYPHS).sort();

export function SocialGlyph({ name, className }) {
  const key = String(name ?? '').toLowerCase();
  const resolved = GLYPHS[key] ? key : (ALIASES[key] ?? 'link');
  const stroked = STROKED.has(resolved);

  return (
    <svg
      viewBox="0 0 24 24"
      className={className}
      aria-hidden="true"
      fill={stroked ? 'none' : 'currentColor'}
      stroke={stroked ? 'currentColor' : 'none'}
      strokeWidth={stroked ? 2 : undefined}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      <path d={GLYPHS[resolved]} />
    </svg>
  );
}

export function SocialLinks({ socials = [], tone = 'light', className }) {
  if (!socials.length) return null;

  return (
    <ul className={cx('flex flex-wrap items-center gap-2.5', className)}>
      {socials.map((social, i) => {
        const external = /^https?:/.test(social.url ?? '');
        return (
          <li key={`${social.url}-${i}`}>
            <a
              href={social.url}
              title={social.label}
              target={external ? '_blank' : undefined}
              rel={external ? 'noopener noreferrer' : undefined}
              className={cx(
                'btn btn-icon size-11',
                tone === 'dark' ? 'bg-white text-ink' : 'bg-white',
              )}
            >
              <SocialGlyph name={social.icon} className="size-[1.15rem]" />
              <span className="sr-only">{social.label}</span>
            </a>
          </li>
        );
      })}
    </ul>
  );
}
